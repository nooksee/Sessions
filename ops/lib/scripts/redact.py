#!/usr/bin/env python3
"""redact: render a public copy of a record. Quoted operator words become their sha256 digest, host
paths and session identifiers (whole or truncated) become numbered placeholders, and everything else
stays byte for byte. A check mode reports what would change and fails closed on anything the rules
cannot classify.

Skeleton generated by ops/bin/template on 2026-11-01; built the same day; revised after the
Independent Reviewer's section 156.
Spec: docs/ops/specs/scripts/redact.md. Tests: tools/test/test_redact.py.

Reads: the record named on the command line, a regular file (never a link), as bytes, decoded as
strict UTF-8. Writes: in render mode only, the public copy at --out and, with --words-out, the
private words file; each is created exclusively (never over an existing file), and a two-output
render writes both or neither. Check mode writes nothing. The tool refuses a
body (`.jsonl`, in any case, through any link) as input: a body is not a record. It refuses its
own public copy as input.

House boundaries: session bodies are not records and are never input here.
Task-local intermediates use var/tmp/; named review-case payload uses
storage/active/; kept results use archives/, archives/receipts/ or custody.
An explicit output path does not grant permission to publish private data.

Usage:
    redact check  RECORD [--decide ID=words|keep|session ...]
    redact render RECORD --out PATH [--words-out PATH] [--decide ID=words|keep|session ...]

Exit codes: 0 classified (check) or written (render); 1 something is unclassified (check lists it,
render refuses); 2 refusal or usage (missing, linked, non-UTF-8 or public-copy input, a body as
input, an existing output or a missing output directory, a write failure, a decision for a span
that is not unclassified).
"""
from __future__ import annotations

import argparse
import hashlib
import os
import re
import sys
from pathlib import Path

SESSIONS = Path(__file__).resolve().parents[3]
SPEC = SESSIONS / "docs" / "ops" / "specs" / "scripts" / "redact.md"
RULES = "8"                                   # bumped whenever a rule below changes; printed in the header
DECISIONS = ("words", "keep", "session")
HEADER_START = "<!-- redact: public copy; "

# Rules. A span is claimed once; earlier rules win: quotes classed as words, then workflow ids, then
# host paths, then whole identifiers, then truncated ones, then bare hex runs. Only a hexadecimal
# neighbour blocks an identifier on its left, so `agent-<id>.jsonl` and `session_<id>` are found; a
# truncated identifier ends at a word boundary, so `abcdef12-dirty` is not one.
HEX = r"[0-9a-f]"
HOST_ROOTS = ("media", "home", "mnt", "tmp", "root", "Users", "var", "opt", "srv", "run")
HOST_START_RE = re.compile(r"(?<![A-Za-z0-9.-])(?:/(?:" + "|".join(HOST_ROOTS) + r")/|~[\w-]*/)")   # an underscore may precede: italics
QUOTE_MARKS = "".join(chr(c) for c in (0x22, 0x201C, 0x201D, 0x201E, 0xAB, 0xBB))   # straight, curly, low, angle
PATH_STOP = set(" \t\r\n`'|]>,;") | set(QUOTE_MARKS)
PATH_TRAIL = ".,:;"
SLUG_RE = re.compile(r"(?<!\w)-(?:" + "|".join(HOST_ROOTS) + r")-[\w-]*")
WF_RE = re.compile(rf"(?<![A-Za-z0-9])wf_{HEX}{{8}}-{HEX}{{3}}(?![\w-])", re.I)   # also inside a name such as journal-wf_...
UUID_RE = re.compile(rf"(?<!{HEX}){HEX}{{8}}-{HEX}{{4}}-{HEX}{{4}}-{HEX}{{4}}-{HEX}{{12}}(?!{HEX})", re.I)
TOKEN_RE = re.compile(rf"(?<!{HEX}){HEX}{{8}}(?:-{HEX}+)+-?", re.I)                      # the maximal hyphenated hex token
LETTER_AND_DIGIT_RE = re.compile(r"(?=[0-9a-f-]*[a-f])(?=[0-9a-f-]*[0-9])", re.I)
HEX_RE = re.compile(rf"(?<!{HEX})(?=[0-9a-f]*[a-f])(?=[0-9a-f]*[0-9]){HEX}{{8,}}(?!{HEX})", re.I)
DIGEST_RE = re.compile(rf"(?<!{HEX})(?:{HEX}{{40}}|{HEX}{{64}})(?!{HEX})", re.I)
URL_RE = re.compile(r"https?://\S+", re.I)
KEEP_LENGTHS = (40, 64)                       # a Git object hash, a sha256
KEEP_CONTEXT = re.compile(r"\b(?:sha256|sha-256|sha|hash|digest|commit|head|merge|blob|tree|object|pr)\s*[:=]?\s*[`(]?\s*$", re.I)
SESSION_CONTEXT = re.compile(r"\b(?:session|body|bodies|donor|container|thread|successor|rotation|spare|uuid)\s*[:=_-]?\s*[`(]?\s*$", re.I)
WORDS_LABEL_RE = re.compile(r"^\s*(?:[-*]\s*)?\*\*([^*]+)\*\*")
WORDS_LABEL_WORDS = re.compile(r"\b(?:words|direction)\b", re.I)
ATTRIBUTION_RE = re.compile(r"\b(?:kevin|operator)\b", re.I)
ATTRIBUTION_WINDOW = 80
FENCE_RE = re.compile(r"^\s*(`{3,}|~{3,})(.*)$")
# A blockquote that quotes the operator (the Independent Reviewer's section 172, C6): a heading, an HTML
# heading, a setext heading or a bold label line that names the operator, the go, the words or a direction,
# and the blockquote under it; or a blockquote line labelled as a go, the words or a direction.
HEADING_RE = re.compile(r"^\s{0,3}#{1,6}\s|^\s*<h[1-6][\s>]", re.I)
ATX_RE = re.compile(r"^\s{0,3}(#{1,6})\s")
HTML_HEADING_RE = re.compile(r"^\s*<h([1-6])[\s>]", re.I)
SETEXT_RE = re.compile(r"^\s{0,3}(?:=+|-+)\s*$")
OPERATOR_NAMED_RE = re.compile(r"(?<![A-Za-z0-9])(?:kevin|operator|go|words|direction)(?![A-Za-z0-9])", re.I)
BLOCKQUOTE_RE = re.compile(r"^\s*(?:(?:[-*+]|\d+[.)])\s+)?(?:>\s*)+")
BLOCKQUOTE_LABEL_RE = re.compile(r"^\s*(?:(?:[-*+]|\d+[.)])\s+)?(?:>\s*)+(?:\*\*|__)?(?:the\s+)?(?:go|words|direction)"
                                 r"(?![A-Za-z0-9])[^:\n]{0,40}:(?:\*\*|__)?\s*", re.I)
LINE_SPLIT_RE = re.compile(r"(\r(?!\n)|\n)")         # a newline, or a carriage return alone (a CR-only record)


class Refused(Exception):
    pass


def sha256(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def span_id(kind: str, text: str) -> str:
    return sha256(f"{kind}\n{text}".encode("utf-8"))[:12]


def span(kind: str, start: int, end: int, text: str, cls, why: str) -> dict:
    return {"kind": kind, "start": start, "end": end, "text": text, "cls": cls, "why": why}


# --------------------------------------------------------------------------
# Finding spans.
# --------------------------------------------------------------------------
def code_regions(line: str) -> list[tuple[int, int]]:
    """Backtick regions, as (start, end) over the characters between the backticks."""
    marks = [i for i, c in enumerate(line) if c == "`"]
    return [(marks[i] + 1, marks[i + 1]) for i in range(0, len(marks) - 1, 2)]


def in_regions(pos: int, regions: list[tuple[int, int]]) -> bool:
    return any(a <= pos < b for a, b in regions)


def eol(line: str) -> int:
    """The end of a line's text: a carriage return before the newline is in no span."""
    return len(line) - 1 if line.endswith("\r") else len(line)


def quote_spans(line: str, history: bool = False) -> list[dict]:
    """Quoted spans outside code, each with its class: 'words', or None when unclassified. In history
    mode every mark counts, code or not, and every quoted stretch is words: the stretch from the first mark
    to the last when the marks are even in number, and the whole line's text when they are odd."""
    code = [] if history else code_regions(line)
    marks = [i for i, c in enumerate(line) if c in QUOTE_MARKS and not in_regions(i, code)]
    label = WORDS_LABEL_RE.match(line)
    if label and WORDS_LABEL_WORDS.search(label.group(1)):
        if (len(marks) >= 2 and len(marks) % 2 == 0
                and not line[label.end():marks[0]].strip()
                and not line[marks[-1] + 1:].strip()):
            a, b = marks[0] + 1, marks[-1]
            return [span("quote", a, b, line[a:b], "words", "a words field")]
        a = label.end()
        while a < len(line) and line[a] == " ":
            a += 1
        why = ("a words field without quote marks" if len(marks) < 2 else
               "a malformed words field: expected one balanced outer quoted payload")
        finding = span("quote", a, eol(line), line[a:eol(line)], "words" if history else None, why)
        finding["words_field"] = True
        return [finding]
    if not marks:
        return []
    if history:
        if len(marks) % 2 == 0:
            a, b = marks[0] + 1, marks[-1]
        else:
            a, b = len(line) - len(line.lstrip()), eol(line)
        return [span("quote", a, b, line[a:b], "words", "a quoted stretch, digested by history mode")]
    spans = []
    for i in range(0, len(marks) - len(marks) % 2, 2):
        a, b = marks[i] + 1, marks[i + 1]
        before = line[max(0, marks[i] - ATTRIBUTION_WINDOW):marks[i]]
        cls = "words" if ATTRIBUTION_RE.search(before) else None
        spans.append(span("quote", a, b, line[a:b], cls, "attributed to the operator" if cls else "[words sha256=8746c4c78c1778ebb72b892888660bcbc0637e3a3368d7387c53b390fe287587]"))
    if len(marks) % 2:
        a = marks[-1] + 1
        spans.append(span("quote", a, eol(line), line[a:eol(line)], None, "an unbalanced quote"))
    return spans


def blockquote_words(lines: list[str]) -> tuple[dict[int, tuple[int, int, str]], set[int]]:
    """The section 172 C6 rule: line index -> (start, end, why) of a words span. Where the quoted text
    begins and ends with a quote mark, the span is the text between them, as a words field's is."""
    out: dict[int, tuple[int, int, str]] = {}
    heads: set[int] = set()                                    # heading or label lines whose blockquote was taken

    def take(k: int, a: int, why: str) -> None:
        line = lines[k]
        b = eol(line)
        while a < b and line[a] in " \t":
            a += 1
        body = line[a:b].rstrip()
        if len(body) >= 2 and body[0] in QUOTE_MARKS and body[-1] in QUOTE_MARKS:
            a, b = a + 1, a + len(body) - 1
        if b > a:
            out[k] = (a, b, why)

    def level(j: int):
        """The heading level of line j (ATX, HTML or setext), or None."""
        cur = lines[j]
        m = ATX_RE.match(cur)
        if m:
            return len(m.group(1))
        m = HTML_HEADING_RE.match(cur)
        if m:
            return int(m.group(1))
        if j + 1 < len(lines) and cur.strip() and not BLOCKQUOTE_RE.match(cur) and SETEXT_RE.match(lines[j + 1]):
            return 1 if "=" in lines[j + 1] else 2
        return None

    why = "a blockquote under a heading or label that names the operator, the go, the words or a direction"
    for k, line in enumerate(lines):
        label = BLOCKQUOTE_LABEL_RE.match(line)
        if label:
            take(k, label.end(), "a blockquote labelled as the operator's go, words or direction")
            continue
        if BLOCKQUOTE_RE.match(line) or not OPERATOR_NAMED_RE.search(line):
            continue
        lv = level(k)
        if lv is not None:                                     # a heading: every blockquote of its section
            j, prev = k + 1, False
            while j < len(lines):
                lj = level(j)
                if lj is not None and lj <= lv:
                    break                                      # the next heading of the same or a higher level
                cur = lines[j]
                bq = BLOCKQUOTE_RE.match(cur)
                if bq:
                    heads.add(k)
                    if j not in out:
                        lab = BLOCKQUOTE_LABEL_RE.match(cur)
                        take(j, lab.end() if lab else bq.end(), why)
                    prev = True
                elif prev and cur.strip() and lj is None:
                    take(j, 0, why + " (a lazy continuation line)")
                else:
                    prev = False
                j += 1
            continue
        if not (WORDS_LABEL_RE.match(line) or line.rstrip().endswith(":")):
            continue                                           # a bold label, or a plain line ending in a colon
        j, in_quote = k + 1, False
        while j < len(lines):
            cur = lines[j]
            if not cur.strip():
                n = j
                while n < len(lines) and not lines[n].strip():
                    n += 1
                if n < len(lines) and BLOCKQUOTE_RE.match(lines[n]) and (in_quote or j == k + 1):
                    j, in_quote = n, False                     # a blank line, then the next blockquote
                    continue
                break
            bq = BLOCKQUOTE_RE.match(cur)
            if bq:
                heads.add(k)
                if j not in out:
                    lab = BLOCKQUOTE_LABEL_RE.match(cur)
                    take(j, lab.end() if lab else bq.end(), why)
                in_quote = True
            elif in_quote and level(j) is None:
                take(j, 0, why + " (a lazy continuation line)")
            else:
                break
            j += 1
    return out, heads


def split_lines(text: str) -> tuple[list[str], list[str]]:
    """Lines and the separator after each: a newline, or a carriage return alone; a CRLF line keeps its
    carriage return at its end, as before."""
    parts = LINE_SPLIT_RE.split(text)
    return parts[0::2], parts[1::2] + [""]


def free(a: int, b: int, taken: list[tuple[int, int]]) -> bool:
    return all(b <= s or a >= e for s, e in taken)


def path_end(line: str, start: int) -> int:
    """Where a host path that starts at `start` ends: through balanced parentheses, and through a
    space when the next segment still carries a slash; trailing sentence punctuation left behind."""
    i, depth = start, 0
    while i < len(line):
        c = line[i]
        if c == " ":
            j = i + 1
            while j < len(line) and line[j] not in PATH_STOP:
                j += 1
            segment = line[i + 1:j]
            if "/" in segment and ":" not in segment and "=" not in segment:
                i = j
                continue
            break
        if c in PATH_STOP:
            break
        if c == "(":
            depth += 1
        elif c == ")":
            if depth == 0:
                break
            depth -= 1
        i += 1
    while i > start and line[i - 1] in PATH_TRAIL:
        i -= 1
    if start > 0 and line[start - 1] == "_":                 # italics: the closing underscores are not the path
        while i > start and line[i - 1] == "_":
            i -= 1
    return i


def hex_spans(line: str, taken: list[tuple[int, int]], record: dict) -> list[dict]:
    """Paths, identifiers and hex runs on one line. `record` holds what the whole record showed:
    the digests written whole, and the session identifiers found anywhere in it."""
    spans = []
    urls = [(m.start(), m.end()) for m in URL_RE.finditer(line)]

    def claim(kind, a, b, cls, why):
        spans.append(span(kind, a, b, line[a:b], cls, why))
        taken.append((a, b))

    for m in WF_RE.finditer(line):
        if free(m.start(), m.end(), taken):
            claim("hex", m.start(), m.end(), "keep", "a workflow id")
    for m in HOST_START_RE.finditer(line):
        a, b = m.start(), path_end(line, m.start())
        if b > a and free(a, b, taken):
            claim("path", a, b, "path", "a host path")
    for m in SLUG_RE.finditer(line):
        if free(m.start(), m.end(), taken):
            claim("path", m.start(), m.end(), "path", "a host path as a project slug")
    for m in UUID_RE.finditer(line):
        if not free(m.start(), m.end(), taken):
            continue
        if in_regions(m.start(), urls):
            claim("session", m.start(), m.end(), None, "an identifier inside a URL")
        else:
            claim("session", m.start(), m.end(), "session", "a session identifier")
    for m in TOKEN_RE.finditer(line):                        # truncated identifiers: the whole token or nothing
        tok = m.group(0)
        if not free(m.start(), m.end(), taken) or not LETTER_AND_DIGIT_RE.match(tok):
            continue                                          # a number such as 20261101-0654 is not an identifier
        before = line[max(0, m.start() - 24):m.start()]
        after = line[m.end()] if m.end() < len(line) else ""
        if in_regions(m.start(), urls):
            claim("prefix", m.start(), m.end(), None, "an identifier inside a URL")
        elif KEEP_CONTEXT.search(before):
            claim("prefix", m.start(), m.end(), "keep", "a digest by its context")
        elif after and (after.isalnum() or after == "_"):
            claim("prefix", m.start(), m.end(), None, "a truncated identifier joined to a word")
        else:
            claim("prefix", m.start(), m.end(), "prefix", "a truncated session identifier")
    for m in HEX_RE.finditer(line):
        if not free(m.start(), m.end(), taken):
            continue
        tok = m.group(0)
        low = tok.lower()
        before = line[max(0, m.start() - 24):m.start()]
        if SESSION_CONTEXT.search(before):
            cls, why = "prefix", "a session prefix by its context"
        elif any(i.startswith(low) for i in record["identifiers"]):
            cls, why = None, "a hex run that heads a session identifier found in this record"
        elif len(tok) in KEEP_LENGTHS:
            cls, why = "keep", "a Git hash" if len(tok) == 40 else "a sha256"
        elif KEEP_CONTEXT.search(before):
            cls, why = "keep", "a digest by its context"
        elif any(d.startswith(low) for d in record["digests"]):
            cls, why = "keep", "the head of a digest written whole in this record"
        else:
            cls, why = None, "a hex run with no context"
        claim("hex", m.start(), m.end(), cls, why)
    return spans


def survey(text: str) -> dict:
    """What the whole record shows before any line is classified."""
    digests = {m.group(0).lower() for m in DIGEST_RE.finditer(text)}
    wf = [(m.start(), m.end()) for m in WF_RE.finditer(text)]
    identifiers = {m.group(0).lower().rstrip("-") for m in UUID_RE.finditer(text)}
    identifiers |= {m.group(0).lower().rstrip("-") for m in TOKEN_RE.finditer(text)
                    if not in_regions(m.start(), wf) and LETTER_AND_DIGIT_RE.match(m.group(0))}
    return {"digests": digests, "identifiers": identifiers}


def decide(s: dict, decisions: dict[str, str], used: set[str], history: bool = False) -> None:
    s["id"] = span_id(s["kind"], s["text"])
    if s["cls"] is None and history:                           # the redacting choice, without a decision
        s["cls"] = "words" if s["kind"] == "quote" else ("session" if s["kind"] == "session" else "prefix")
        s["why"] += "; redacted by history mode"
        return
    if s["cls"] is None and s["id"] in decisions:
        d = decisions[s["id"]]
        if s.get("words_field") and d != "words":
            raise Refused(f"decision {s['id']} cannot keep a known words field")
        if s["kind"] == "quote" and d == "session":
            raise Refused(f"decision {s['id']}=session names a quote; a quote is words or keep")
        if s["kind"] != "quote" and d == "words":
            raise Refused(f"decision {s['id']}=words names a {s['kind']}; only a quote is words")
        if d == "session":
            s["cls"] = "session" if s["kind"] == "session" else "prefix"
        else:
            s["cls"] = d
        s["why"] = f"decided {d}"
        used.add(s["id"])


def next_fence(line: str, current):
    """Retain the opening marker and length; only its valid closing marker ends it."""
    m = FENCE_RE.match(line)
    if not m:
        return current
    marker, tail = m.groups()
    if current is not None:
        char, length = current
        if marker[0] == char and len(marker) >= length and not tail.strip():
            return None
        return current
    # Preserve the existing same-line/code-span behavior, including the
    # backtick info-string restriction. Do not let a literal opposite marker
    # or a shorter marker close an already active fenced block.
    if marker[0] == "`" and "`" in tail:
        return None
    return marker[0], len(marker)


def classify(text: str, decisions: dict[str, str], history: bool = False) -> tuple[list[dict], set[str]]:
    """Every span of the record, in document order, with its class; returns (spans, decision ids used).
    Quotes are decided before the hex pass, so a kept or undecided quote still has the identifiers
    and paths inside it claimed and placeholdered; only a words span is digested whole."""
    spans, used = [], set()
    record = survey(text)
    fence = None
    lines, _ = split_lines(text)
    quoted, quote_heads = blockquote_words(lines)
    for n, line in enumerate(lines, 1):
        following_fence = next_fence(line, fence)
        if n - 1 in quoted:
            a, b, why = quoted[n - 1]
            quotes = [span("quote", a, b, line[a:b], "words", why)]
        elif history:
            quotes = quote_spans(line, history=True)
        else:
            quotes = [] if fence is not None or following_fence is not None else quote_spans(line)
        if n - 1 in quote_heads:                               # an empty words label over a taken blockquote is a heading
            quotes = [q for q in quotes if not (q.get("words_field") and not q["text"].strip())]
        fence = following_fence
        for s in quotes:
            decide(s, decisions, used, history)
        taken = [(s["start"], s["end"]) for s in quotes if s["cls"] == "words"]
        hexes = hex_spans(line, taken, record)
        for s in hexes:
            decide(s, decisions, used, history)
        for s in sorted(quotes + hexes, key=lambda s: (s["start"], -s["end"])):
            s["line"] = n
            spans.append(s)
    # The second pass: no kept run may equal or head an identifier this record placeholders, whatever
    # placed that identifier (shape, context or decision); a decision that would keep one is refused.
    placeholdered = {s["text"].lower().rstrip("-") for s in spans if s["cls"] in ("session", "prefix")}
    for s in spans:
        if s["cls"] != "keep" or s["kind"] == "quote":
            continue
        t = s["text"].lower().rstrip("-")
        if any(p.startswith(t) or t.startswith(p) for p in placeholdered):
            if s["why"].startswith("decided"):
                raise Refused(f"decision {s['id']}=keep would keep a run that matches a session identifier placeholdered in this record")
            s["cls"], s["why"] = None, "a kept run that matches a session identifier placeholdered in this record"
            decide(s, decisions, used, history)
            if s["cls"] == "keep":
                raise Refused(f"decision {s['id']}=keep would keep a run that matches a session identifier placeholdered in this record")
    return spans, used


# --------------------------------------------------------------------------
# Numbering and rendering.
# --------------------------------------------------------------------------
def number(spans: list[dict]) -> None:
    sessions: dict[str, int] = {}
    paths: dict[str, int] = {}
    full = [s["text"].lower() for s in spans if s["cls"] == "session"]
    for s in spans:
        if s["cls"] == "session":
            s["n"] = sessions.setdefault(s["text"].lower(), len(sessions) + 1)
        elif s["cls"] == "prefix":
            head = s["text"].lower().rstrip("-")
            key = next((f for f in full if f.startswith(head)), head[:8])   # the same head is the same body
            s["n"] = sessions.setdefault(key, len(sessions) + 1)
        elif s["cls"] == "path":
            s["n"] = paths.setdefault(s["text"], len(paths) + 1)


def replacement(s: dict) -> str | None:
    if s["cls"] == "words":
        return f"[words sha256={sha256(s['text'].encode('utf-8'))}]"
    if s["cls"] == "path":
        return f"[host path {s['n']}]"
    if s["cls"] == "session":
        return f"[session {s['n']}]"
    if s["cls"] == "prefix":
        return f"[session prefix {s['n']}]"
    return None                                               # keep


def render(text: str, spans: list[dict]) -> str:
    lines, seps = split_lines(text)
    by_line: dict[int, list[dict]] = {}
    for s in spans:
        if replacement(s) is not None:
            by_line.setdefault(s["line"], []).append(s)
    for n, group in by_line.items():
        line = lines[n - 1]
        for s in sorted(group, key=lambda s: s["start"], reverse=True):
            line = line[:s["start"]] + replacement(s) + line[s["end"]:]
        lines[n - 1] = line
    return "".join(line + sep for line, sep in zip(lines, seps))


def counts(spans: list[dict]) -> dict[str, int]:
    return {"words": sum(s["cls"] == "words" for s in spans),
            "sessions": sum(s["cls"] == "session" for s in spans),
            "truncated": sum(s["cls"] == "prefix" for s in spans),
            "paths": sum(s["cls"] == "path" for s in spans),
            "kept_rule": sum(s["cls"] == "keep" and not s["why"].startswith("decided") for s in spans),
            "kept_decision": sum(s["cls"] == "keep" and s["why"].startswith("decided") for s in spans),
            "unclassified": sum(s["cls"] is None for s in spans)}


def preview(s: dict) -> str:
    """Never the words; a path or a run by its head only, since either may carry an identifier."""
    if s["kind"] == "quote":
        return f"{len(s['text'])} characters"
    if s["kind"] == "path":
        return s["text"][:8] + ("..." if len(s["text"]) > 8 else "") + f" ({len(s['text'])} characters)"
    return s["text"][:8] + ("..." if len(s["text"]) > 8 else "")


def report(spans: list[dict], out) -> None:
    for s in spans:
        if s["cls"] is None:
            print(f"line {s['line']}: UNCLASSIFIED {s['kind']} [id {s['id']}]: {s['why']}, {preview(s)}", file=out)
        elif s["cls"] == "words":
            print(f"line {s['line']}: words -> sha256={sha256(s['text'].encode('utf-8'))[:16]}... ({len(s['text'])} characters; {s['why']})", file=out)
        elif s["cls"] == "keep":
            print(f"line {s['line']}: kept {s['kind']} [id {s['id']}] ({s['why']}, {preview(s)})", file=out)
        elif s["cls"] == "path":
            print(f"line {s['line']}: host path -> [host path {s['n']}]: {preview(s)}", file=out)
        else:
            print(f"line {s['line']}: {'session' if s['cls'] == 'session' else 'session prefix'} -> [session{' prefix' if s['cls'] == 'prefix' else ''} {s['n']}]: {preview(s)}", file=out)



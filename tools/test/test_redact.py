#!/usr/bin/env python3
"""Tests for ops/lib/scripts/redact.py, on synthetic inputs only. Standard library only.

Skeleton generated by ops/bin/template on 2026-11-01; built the same day. No real body, record,
path or identifier is used: the identifiers are UUID-shaped values with zero blocks, the paths are
under /home/example and /media/example. Run:

    python3 -I -B tools/test/test_redact.py

Behavior cases: words lines are digested; an attributed quote is digested; an unattributed quote
fails closed; host paths and session identifiers, whole and truncated, become numbered placeholders;
sha256 and Git hashes stay; byte-for-byte elsewhere; check writes nothing; render refuses an existing
output; decisions by span id.
"""
import hashlib
import importlib.util
import os
import re
import stat
import subprocess
import sys
import tempfile
import unittest
from pathlib import Path

TOOL = Path(__file__).resolve().parents[2] / "ops" / "lib" / "scripts" / "redact.py"
SCRATCH = Path(__file__).resolve().parents[2] / "var" / "tmp"
UUID = "0000abcd-0000-4000-8000-00000000abcd"
UUID2 = "0000beef-0000-4000-8000-00000000beef"
SHA = "a1b2c3d4" * 8                          # 64 hex characters with letters and digits throughout
GIT = "b2c3d4e5" * 5                          # 40


def sha256(text: str) -> str:
    return hashlib.sha256(text.encode("utf-8")).hexdigest()


def run(*args):
    return subprocess.run([sys.executable, "-I", "-B", str(TOOL), *args], capture_output=True, text=True, timeout=60)


class RedactTests(unittest.TestCase):
    def setUp(self):
        SCRATCH.mkdir(parents=True, exist_ok=True)
        self.tmp = tempfile.TemporaryDirectory(prefix="redact-test-", dir=SCRATCH)
        self.dir = Path(self.tmp.name)

    def tearDown(self):
        self.tmp.cleanup()

    def record(self, text: str, name: str = "record.md") -> Path:
        p = self.dir / name
        p.write_bytes(text.encode("utf-8"))
        return p

    def rendered(self, text: str, *decide) -> tuple[str, subprocess.CompletedProcess]:
        rec = self.record(text)
        out = self.dir / "public.md"
        r = run("render", str(rec), "--out", str(out), *[a for d in decide for a in ("--decide", d)])
        return (out.read_bytes().decode("utf-8") if out.exists() else ""), r      # bytes, so CRLF survives the read

    def keep_blocks(self, text: str, name: str = "keep-blocks.md") -> list:
        """The keep decisions for every open block (a fence or a neutral blockquote) the check names."""
        r = run("check", str(self.record(text, name)))
        ids = re.findall(r"UNCLASSIFIED quote \[id ([0-9a-f]{12})\]: a (?:fenced block|blockquote) that no rule classifies", r.stdout)
        return [f"{i}=keep" for i in dict.fromkeys(ids)]

    def body(self, public: str) -> str:
        """The rendered text without the header line."""
        self.assertTrue(public.startswith("<!-- redact: public copy; source sha256 "), public[:80])
        return public.split("\n", 1)[1]

    # -- words --------------------------------------------------------------
    def test_p1_unbalanced_words_field_never_renders_a_public_tail(self):
        text = '- **Words:** "the "role" must remain private\n'
        rec = self.record(text)
        checked = run("check", str(rec))
        self.assertEqual(checked.returncode, 1, checked.stdout + checked.stderr)
        public, rendered = self.rendered(text)
        self.assertEqual(rendered.returncode, 1, rendered.stdout + rendered.stderr)
        self.assertEqual(public, "")
        self.assertNotIn("must remain private", checked.stdout + checked.stderr)

    def test_p1_words_field_requires_only_the_outer_quoted_payload(self):
        for index, text in enumerate((
            '- **Words:** prefix "quoted fragment"\n',
            '- **Words:** "quoted fragment" private tail\n',
            '- **Words:** "quoted fragment\n',
        )):
            with self.subTest(case=index):
                rec = self.record(text, "malformed-%s.md" % index)
                result = run("render", str(rec), "--out", str(self.dir / ("out-%s.md" % index)))
                self.assertEqual(result.returncode, 1, result.stdout + result.stderr)
                self.assertFalse((self.dir / ("out-%s.md" % index)).exists())

    def test_p1_known_malformed_words_cannot_be_decided_keep(self):
        text = '- **Words:** "invented private words" trailing text\n'
        rec = self.record(text)
        checked = run("check", str(rec))
        decision = re.search(r"\[id ([0-9a-f]{12})\]", checked.stdout).group(1)
        out = self.dir / "public.md"
        result = run("render", str(rec), "--out", str(out), "--decide", decision + "=keep")
        self.assertEqual(result.returncode, 2, result.stdout + result.stderr)
        self.assertIn("known words field", result.stderr)
        self.assertFalse(out.exists())

    def test_p1_malformed_words_can_only_be_explicitly_digested_whole(self):
        text = '- **Words:** "invented private words" trailing text\n'
        rec = self.record(text)
        checked = run("check", str(rec))
        decision = re.search(r"\[id ([0-9a-f]{12})\]", checked.stdout).group(1)
        out = self.dir / "public.md"
        result = run("render", str(rec), "--out", str(out), "--decide", decision + "=words")
        self.assertEqual(result.returncode, 0, result.stdout + result.stderr)
        public = out.read_text(encoding="utf-8")
        self.assertNotIn("invented private words", public)
        self.assertNotIn("trailing text", public)
        self.assertIn('[words sha256=%s]' % sha256('"invented private words" trailing text'), public)

    def test_p1_mixed_fence_markers_do_not_expose_following_prose(self):
        words = "invented private note after the fence"
        text = '~~~markdown\n```\n~~~\nKevin: "%s"\n' % words
        public, result = self.rendered(text, *self.keep_blocks(text))
        self.assertEqual(result.returncode, 0, result.stdout + result.stderr)
        self.assertNotIn(words, public)
        self.assertIn('[words sha256=%s]' % sha256(words), public)

    def test_p1_short_fence_does_not_close_a_long_opening_marker(self):
        inside = "invented code text"
        outside = "invented prose text"
        text = '````markdown\n```\nKevin: "%s"\n````\nKevin: "%s"\n' % (inside, outside)
        public, result = self.rendered(text, *self.keep_blocks(text))
        self.assertEqual(result.returncode, 0, result.stdout + result.stderr)
        self.assertIn(inside, public)
        self.assertNotIn(outside, public)

    def test_p1_matching_fence_can_close_with_a_longer_marker(self):
        words = "invented outside fence note"
